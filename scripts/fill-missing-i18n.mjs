const zhCNMap = parse('zh-CN.po')
const files = fs.readdirSync(localeDir).filter(f => f.endsWith('.po') && f !== 'en-US.po')

let totalAdded = 0, totalFilled = 0
for (const file of files) {
  const have = parse(file)
  const locale = file.replace('.po', '')
  let dict
  if (locale === 'en-GB') dict = { ...baseMap, ...NEW }
  else if (locale === 'zh-CN') dict = { ...zhCNMap, ...NEW_ZH }
  else dict = D[locale]
  if (!dict) continue

  let raw = fs.readFileSync(path.join(localeDir, file), 'utf8')
  let out = raw

  // 1) 填補空翻譯（settings.hotkeyConflictConfirm 等）
  for (const key of Object.keys(dict)) {
    if (key in have && have[key].trim() === '' && dict[key] != null) {
      const re = new RegExp('msgid "' + escRe(key) + '"\\nmsgstr ""')
      if (re.test(out)) {
        out = out.replace(re, 'msgid "' + key + '"\nmsgstr "' + poEscape(dict[key]) + '"')
        totalFilled++
      }
    }
  }

  // 2) 追加缺失 key
  let appended = ''
  for (const key of TARGET_KEYS) {
    if (!(key in have) && dict[key] != null) {
      appended += 'msgid "' + key + '"\nmsgstr "' + poEscape(dict[key]) + '"\n\n'
      totalAdded++
    }
  }
  if (appended) {
    out = out.replace(/\s*$/, '\n\n') + appended
  }

  fs.writeFileSync(path.join(localeDir, file), out, 'utf8')
}

