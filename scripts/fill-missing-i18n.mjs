import fs from 'fs'
import path from 'path'

const __dirname = path.dirname(new URL(import.meta.url).pathname.replace(/^\/(\w:)/, '$1'))
const localeDir = path.resolve(__dirname, '../locale')

// 正确的 .po 解析（单/多行msgstr 均兼容）
function parse(file) {
  const txt = fs.readFileSync(path.join(localeDir, file), 'utf8')
  const map = {}
  const lines = txt.split(/\r?\n/)
  let cur = null, val = ''
  for (const line of lines) {
    const m = line.match(/^msgid\s+"(.*)"\s*$/)
    const m2 = line.match(/^msgstr\s+"(.*)"\s*$/)
    if (m) {
      if (cur !== null) map[cur] = val
      cur = m[1]
      val = ''
    } else if (m2) {
      val = m2[1]
    } else if (cur !== null && line.startsWith('"') && line.endsWith('"')) {
      val += line.slice(1, -1)
    }
  }
  if (cur !== null) map[cur] = val
  return map
}

function poEscape(s) {
  return String(s)
    .replace(/\\/g, '\\\\')
    .replace(/"/g, '\\"')
    .replace(/\r/g, '')
    .replace(/\n/g, '\\n')
}

function escRe(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
}

